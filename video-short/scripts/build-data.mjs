/**
 * Read the committed artifacts and emit src/data.generated.js.
 *
 * The film is drawn in a browser canvas, so it cannot read ml/artifacts/*.json at render
 * time the way the app does. This closes that gap instead of inviting someone to type the
 * numbers into a shot: every figure on screen originates here, and `npm run data` is a
 * prerequisite of `npm run render`.
 *
 * Same rule as the app and the 3-minute video — a figure that disagrees with its artifact
 * is a bug, not a wording choice.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ART = resolve(HERE, "..", "..", "ml", "artifacts");
const read = (f) => JSON.parse(readFileSync(join(ART, f), "utf8"));

const metrics = read("metrics.json");
const mag = read("magnitude_metrics.json");
const conf = read("confidence_tiers.json");
const ledger = read("holdout_ledger.json");
const signals = read("latest_signals.json");

const pct = (x, places = 2) => `${(x * 100).toFixed(places)}%`;
const int = (n) => n.toLocaleString("en-US");

const d = metrics.direction;
const ab = metrics.abstention;
const hc = conf.holdout_comparison;
const prov = metrics.provenance ?? {};

const data = {
  // Direction head, final holdout — the honest headline.
  holdoutAcc: pct(d.accuracy),
  holdoutN: int(d.n),
  auc: d.auc.toFixed(4),

  // Abstention.
  gate: ab.threshold.toFixed(2),
  coverage: pct(ab.coverage, 1),
  abstainShare: pct(1 - ab.coverage, 1),
  accWhenCalling: pct(ab.accuracy_when_signalling),

  // The validation-optimism tax.
  valAcc: pct(hc.validation_accuracy),
  gap: `${(hc.gap * 100).toFixed(2)} pts`,

  // Magnitude head.
  magMedian: pct(mag.summary.accuracy_when_calling_median),
  magWindows: `${mag.summary.windows_at_or_above_60pct} of ${mag.summary.windows_total}`,

  // Provenance.
  rows: int(prov.panel_rows ?? 0),
  features: String(prov.feature_count ?? 0),
  universe: String(signals.universe_size),
  holdoutReads: String(ledger.authoritative_reads),

  // Today's board.
  callsToday: String(signals.summary.signals_emitted),
  abstainedToday: String(signals.summary.abstained),
};

const out = `// GENERATED by scripts/build-data.mjs — do not edit.
// Every figure is read from ml/artifacts/. Regenerate with \`npm run data\`.
export const D = ${JSON.stringify(data, null, 2)};
`;

mkdirSync(resolve(HERE, "..", "src"), { recursive: true });
writeFileSync(resolve(HERE, "..", "src", "data.generated.js"), out);
console.log("wrote src/data.generated.js");
for (const [k, v] of Object.entries(data)) console.log(`  ${k.padEnd(16)} ${v}`);
